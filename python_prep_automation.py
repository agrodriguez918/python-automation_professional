# Load libraries
import os
import re
import win32com.client as win32
from datetime import datetime, timedelta

# email to finance department requesting signatures for Pharmacy Rx + OTC file attestations

# Store parent directory paths
CATEGORY_PATHS = {
    "Pharmacy" : r"file_path",
    "OTC" : r"file_path"
}

# email configuration
CSV_PATTERN = r".*\csv$"
RX_ENC_PATTERN = r"^PDF.*\.pdf$"
OTC_ENC_PATTERN = r"^FCC_Attestation_Signed.*\.pdf$"

EMAIL_RECIPIENT = [email_addresses]
EMAIL_CC = [email_addresses]
EMAIL_SUBJECT = "Provider_Name Pharmacy & Provider_Name OTC (LTC & MMA) Attestations - {date}"
EMAIL_BODY = (
    "Good afternoon, \n\nPlease see attached Provider_Name Pharmacy/HIV/SMI & Provider_Name OTC attestation files. Please sign the signature page attestation file. ({attestation_count} ATTESTATIONS)\n\nDue date for the signature is: {tmr} by COB.\n\nThank you!\n\nBest, \nName" )

LOG_FILE = "Signature_email_log.txt"

# get input for the date
submission_date = input("Enter submission date (MM-DD-YYYY): ").strip()

# validate input date
try:
  date_obj = datetime.strptime(submission_date, "%m-%d-%Y")
except ValueError:
  print("Invalid date format. Please use MM-DD-YYYY.")
  exit()

year_folder = date_obj.strftime("%Y")
month_folder = date_obj.strftime("%m")
tmrs_date = (date_obj + timedelta(days = 1)).strftime("%m-%d-%Y")

all_files_to_attach = []
attestation_count = 0

# search for folders in both pharmacy and otc folder paths

for category, base_path in CATEGORY_PATHS.items():
  year_path = os.path.join(base_path, year_folder)
  if not os.path.exists(year_path):
    continue

  search_roots = []
  if category == "OTC":
    for subfolder in ["MMA", "LTC"]:
      sub_path = os.path.join(year_path, subfolder)
      if os.path.exists(sub_path):
        search_roots.append(sub_path)

  else:
    search_roots.append(year_path)

  for root in search_roots:

    month_candidates = [
        os.path.join(root, entry)
        for entry in os.listdir(root)
        if os.path.isdir(os.path.join(root, entry)) and entry.startswith(month_folder)
    ]

    for search_path in month_candidates:

      matching_folders = [
          os.path.join(search_path, entry)
          for entry in os.listdir(search_path)
          if os.path.isdir(os.path.join(search_path, entry)) and submission_date in entry
      ]


      for folder in matching_folders:
        files_in_folder = os.listdir(folder)

        csv_file = next((os.path.join(folder, f) for f in files_in_folder if re.match(CSV_PATTERN, f)), None)
        if csv_file:
          all_files_to_attach.append(csv_file)

        enc_pattern = RX_ENC_PATTERN if category == "Pharmacy" else OTC_ENC_PATTERN

        enc_file = next((os.path.join(folder, f) for f in files_in_folder if re.match(enc_pattern, f)), None)
        if enc_file:
          all_files_to_attach.append(enc_file)
          attestation_count += 1

if not all_files_to_attach:
  print("No files found for the given date. Email not send.")
else:
  outlook = win32.Dispatch("Outlook.Application")
  subject = EMAIL_SUBJECT.format(date = submission_date)
  body = EMAIL_BODY.format(
      date=submission_date,
      tmr=tmrs_date,
      attestation_count=attestation_count
  )

  mail = outlook.CreateItem(0)
  mail.To = "; ".join(EMAIL_RECIPIENT)
  mail.CC = "; ".join(EMAIL_CC)
  mail.Subject = subject
  mail.Body = body

  for f in all_files_to_attach:
    mail.Attachments.Add(f)
  mail.Send()

  with open(LOG_FILE, "a") as log:
    log.write(f"{datetime.now()} - Sent to {EMAIL_RECIPIENT} CC: {EMAIL_CC}| Subject: {subject} | Body: {body} | Files: {', '.join(all_files_to_attach)}\n")

  print(f"email sent. Log saved to {LOG_FILE}.")


