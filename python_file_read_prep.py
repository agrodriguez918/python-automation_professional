# rewrites the date values in columns A, I, and J to the correct format (mm/dd/YYYY)
def rewrite_otc_local_csv(csv_path, dry_run=False):
  df = pd.read_csv(csv_path)
  changed = False
  for col in ["UPLOAD_DATE", " EARLIST_DATE", " LATEST_DATE"]:
    if col in df.columns:
      original = str(df.at[0, col])
      reform = normalize_from_yymmdd(original)
      if reform != original:
        df.at[0, col] = reform
        changed = True

# sets the dry run to display the headers and first row of each .csv it would modify
  if dry_run:
    print(f"[DRY RUN] OTC CSV date normalization for {csv_path}:")
    print(df.head(1))
