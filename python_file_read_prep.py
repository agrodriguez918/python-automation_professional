# creates and inserts required rows into .xlsx tracker above label "TOTAL"
def insert_rows_and_fill_history(tracker_path, sheet_name, rows_of_values, dry_run=False):
  if dry_run:
    print(f"[DRY RUN] Would insert {len(rows_of_values)} rows into {sheet_name}")
    for row in rows_of_values:
      print(f"  Row: {row}")
    return True
  wb = load_workbook(tracker_path)
  ws = wb[sheet_name]

# inserts one row above the row starting with the label "TOTAL" in column A
  total_row = next((r for r in range(1, ws.max_row + 1) if isinstance(ws.cell(row=r, column=1).value, str) and ws.cell(row=r, column=1).value.strip().upper() == "TOTAL"), ws.max_row + 1)
  ws,insert_rows(total_row, amount=len(rows_of_values))

# inserts for each folder we saved values from
  for i, row_vals in enumerate(rows_of_values):
    for col_letter, value in row_vals.items():
      ws[f"{col_letter}{total_row + i}"] = value
  wb.save(tracker_path)
  return True

